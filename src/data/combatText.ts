export function normalizeCombatText(text: string): string {
  return text
    .replace(/随机爆破\s*一颗的宝石/g, '随机选择一颗宝石爆破')
    .replace(/溅射上海/g, '溅射伤害')
    .replace(/(?:严重|重度|大量)(?:的)?\s*溅射/g, '重度溅射')
    .replace(/(?:轻微|轻度)(?:的)?\s*溅射/g, '轻度溅射')
    .replace(/溅射真实伤害/g, '真实溅射伤害')
    .replace(/(轻度|重度)真实溅射/g, '真实$1溅射')
    .replace(/并或使其/g, '并使其')
    .replace(/所受的到的/g, '所受的')
    .replace(/被我的法术击到敌人/g, '被该技能命中的敌人')
    .replace(/\b(\d+)\s*[xX]\s*(\d+)\b/g, '$1×$2')
    .replace(/([\u4e00-\u9fff])[ \t]+(?=[\u4e00-\u9fff])/g, '$1')
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/\s+([，。；：])/g, '$1')
    .trim();
}

export function spellDescription(id: number, source: string): string {
  let text = PROJECT_SPELL_TEXT[id] ?? source;
  const rule = (damageRules as Record<number, { splash?: number[]; scatter?: boolean }>)[id];
  if (rule?.splash) {
    let index = 0;
    text = text.replace(/(?:(?:严重|轻微|重度|轻度|大量|轻量|光)(?:的)?\s*)?(真实)?(?:溅射|散射)/g, (_match, truePrefix: string | undefined) => {
      const ratio = rule.splash![Math.min(index++, rule.splash!.length - 1)];
      return (truePrefix ?? '') + (ratio === 0.25 ? '轻度溅射' : ratio === 0.75 ? '重度溅射' : '溅射');
    });
  }
  if (rule?.scatter) text = text.replace(/(?:(?:严重|轻微|重度|轻度|大量)(?:的)?\s*)?溅射/g, '散射');
  return normalizeCombatText(text);
}
